/**
 * Render the 2D configurator images from the 3D models.
 *
 * For every bag: front and back in each denim wash (Stella in layers: body,
 * strap + tab, rings, which the page stacks), and the open bag seen from
 * above in each wash × lining. Writes transparent WebP files to
 * public/bags2d/<bag>/, wash swatches to public/bags2d/swatches/, and the
 * image frames (where the body sits in each view, so patches and the
 * monogram line up) to app/utils/stella/frames.ts.
 *
 * Re-run after changing a model, a wash or a lining:
 *   node scripts/render-bags-2d.mjs [bagId ...]
 * RENDER_ONLY=top renders only the files whose name contains "top".
 * Uses Playwright's Chromium (set CHROMIUM_PATH to use another binary).
 */
import { build } from 'vite'
import { chromium } from 'playwright'
import { createServer } from 'node:http'
import { mkdirSync, readFileSync, writeFileSync, existsSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SIZE = 1200
const OUT = join(ROOT, 'public', 'bags2d')
const only = process.argv.slice(2)

// 1. Bundle the browser entry (three.js + the configurator code).
const dist = mkdtempSync(join(tmpdir(), 'linea2-render-'))
await build({
  configFile: false,
  logLevel: 'warn',
  build: {
    outDir: dist,
    emptyOutDir: true,
    minify: false,
    lib: { entry: join(ROOT, 'scripts/render-2d/entry.ts'), formats: ['es'], fileName: () => 'entry.js' },
  },
})
writeFileSync(join(dist, 'index.html'), '<!doctype html><body style="margin:0"><div id="host" style="width:600px;height:600px"></div><script type="module" src="/entry.js"></script>')

// 2. Serve it with the models next to it.
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.glb': 'model/gltf-binary' }
const server = createServer((req, res) => {
  const path = decodeURIComponent((req.url ?? '/').split('?')[0])
  const file = path.startsWith('/models/') ? join(ROOT, 'public', path) : join(dist, path === '/' ? 'index.html' : path)
  if (!existsSync(file)) return void res.writeHead(404).end()
  res.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream' }).end(readFileSync(file))
}).listen(0)
const url = `http://localhost:${server.address().port}/`

// 3. Render.
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'],
})
const page = await browser.newPage()
page.on('pageerror', (e) => console.error('page error:', e.message))
await page.goto(url)
await page.waitForFunction(() => Array.isArray(window.bagIds))
await page.evaluate(() => document.fonts.ready)

const save = (file, dataUrl) => {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, Buffer.from(dataUrl.split(',')[1], 'base64'))
}

const framesFile = join(ROOT, 'app/utils/stella/frames.ts')
const frames = existsSync(framesFile)
  ? JSON.parse(readFileSync(framesFile, 'utf8').match(/= (\{[\s\S]*\})\s*$/)[1])
  : {}
const ids = (await page.evaluate(() => window.bagIds)).filter((id) => !only.length || only.includes(id))
for (const id of ids) {
  const t = Date.now()
  const { out, frames: f } = await page.evaluate(([id, size, only]) => window.renderBag(id, size, only), [id, SIZE, process.env.RENDER_ONLY ?? ''])
  for (const [name, data] of Object.entries(out)) save(join(OUT, id, `${name}.webp`), data)
  frames[id] = { ...frames[id], ...f }
  console.log(`${id}: ${Object.keys(out).length} images in ${((Date.now() - t) / 1000).toFixed(0)}s`)
}
for (const [name, data] of Object.entries(await page.evaluate(() => window.swatches()))) save(join(OUT, 'swatches', `${name}.png`), data)

const round = (o) => JSON.parse(JSON.stringify(o, (_, v) => (typeof v === 'number' ? Math.round(v * 10000) / 10000 : v)))
writeFileSync(
  framesFile,
  `// Generated by scripts/render-bags-2d.mjs — do not edit by hand.\nimport type { BagView, Frame } from './options'\n\nexport const FRAMES: Record<string, Partial<Record<BagView, Frame>>> = ${JSON.stringify(round(frames), null, 2)}\n`,
)
await browser.close()
server.close()
